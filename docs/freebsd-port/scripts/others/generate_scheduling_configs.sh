#!/bin/bash

# generate_scheduling_configs.sh
# 
# Generates ZFS and BFQ config files in the current directory.
# Does NOT require root. Does NOT apply anything live.
#
# After running, manually copy files as root:
#   sudo cp zfs-io-priority.conf /etc/modprobe.d/
#   sudo cp 70-io-scheduler.rules /etc/udev/rules.d/
#   sudo udevadm control --reload-rules && sudo udevadm trigger --subsystem-match=block
#
# Target drives: sd[c-g] (SMR drives)

set -eu

echo "Generating scheduling config files in: $(pwd)"
echo

# --- File 1: ZFS I/O priority config ---
cat > zfs-io-priority.conf <<'EOF'
# ZFS I/O Priority Tuning
# Generated by generate_scheduling_configs.sh
# 
# Goal: Guarantee write throughput for stability, serialize reads to reduce
#       head thrashing on SMR drives, and prevent read-heavy workloads
#       from starving critical ZFS writes (txg commits).
#
# These settings apply per leaf vdev (physical disk).
# This file is SEPARATE from zfs.conf (won't overwrite your arc/txg settings).

# Limit sync operations to 1 lane each (serialized)
options zfs zfs_vdev_sync_read_min_active=1
options zfs zfs_vdev_sync_read_max_active=1
options zfs zfs_vdev_sync_write_min_active=1
options zfs zfs_vdev_sync_write_max_active=1

# Limit async reads to 1 lane (Storj + Torrent share this)
options zfs zfs_vdev_async_read_min_active=1
options zfs zfs_vdev_async_read_max_active=1

# Guarantee 4 lanes for async writes (txg commits)
options zfs zfs_vdev_async_write_min_active=4
options zfs zfs_vdev_async_write_max_active=10

# Scrub stays low priority
options zfs zfs_vdev_scrub_min_active=1
options zfs zfs_vdev_scrub_max_active=2
EOF

echo "Created: zfs-io-priority.conf"

# --- File 2: BFQ udev rules ---
cat > 70-io-scheduler.rules <<'EOF'
# BFQ Scheduler for SMR HDDs (sd[c-g])
# Generated by generate_scheduling_configs.sh
#
# Provides deadlines and batching at block layer.
# Note: ionice is ineffective with ZFS (kernel threads don't inherit priority).
# Real priority control happens at ZFS layer (zfs-io-priority.conf).

# Scheduler selection
ACTION=="add|change", SUBSYSTEM=="block", KERNEL=="sd[c-g]", ATTR{queue/scheduler}="bfq"

# Priority enforcement
ACTION=="add|change", SUBSYSTEM=="block", KERNEL=="sd[c-g]", ATTR{queue/iosched/low_latency}="1"
ACTION=="add|change", SUBSYSTEM=="block", KERNEL=="sd[c-g]", ATTR{queue/iosched/strict_guarantees}="1"

# Deadlines: 200ms for reads, 2000ms for writes
ACTION=="add|change", SUBSYSTEM=="block", KERNEL=="sd[c-g]", ATTR{queue/iosched/timeout_sync}="200"
ACTION=="add|change", SUBSYSTEM=="block", KERNEL=="sd[c-g]", ATTR{queue/iosched/fifo_expire_sync}="200"
ACTION=="add|change", SUBSYSTEM=="block", KERNEL=="sd[c-g]", ATTR{queue/iosched/fifo_expire_async}="2000"

# Read-ahead: moderate (ZFS does its own prefetch)
ACTION=="add|change", SUBSYSTEM=="block", KERNEL=="sd[c-g]", ATTR{queue/read_ahead_kb}="512"
EOF

echo "Created: 70-io-scheduler.rules"

# --- Done ---
echo
echo "=============================================="
echo "  Files generated. Next steps:"
echo "=============================================="
echo
echo "1. Review the files:"
echo "   cat zfs-io-priority.conf"
echo "   cat 70-io-scheduler.rules"
echo
echo "2. Copy as root:"
echo "   sudo cp zfs-io-priority.conf /etc/modprobe.d/"
echo "   sudo cp 70-io-scheduler.rules /etc/udev/rules.d/"
echo
echo "3. Apply udev rules live:"
echo "   sudo udevadm control --reload-rules"
echo "   sudo udevadm trigger --subsystem-match=block"
echo
echo "4. (Optional) Apply ZFS settings live without reboot:"
echo "   for p in zfs_vdev_sync_read_min_active zfs_vdev_sync_read_max_active \\"
echo "            zfs_vdev_sync_write_min_active zfs_vdev_sync_write_max_active \\"
echo "            zfs_vdev_async_read_min_active zfs_vdev_async_read_max_active; do"
echo "     echo 1 | sudo tee /sys/module/zfs/parameters/\$p"
echo "   done"
echo "   echo 4 | sudo tee /sys/module/zfs/parameters/zfs_vdev_async_write_min_active"
echo "   echo 10 | sudo tee /sys/module/zfs/parameters/zfs_vdev_async_write_max_active"
echo "   echo 1 | sudo tee /sys/module/zfs/parameters/zfs_vdev_scrub_min_active"
echo "   echo 2 | sudo tee /sys/module/zfs/parameters/zfs_vdev_scrub_max_active"
echo
echo "Note: Your existing /etc/modprobe.d/zfs.conf (arc, txg settings) is untouched."
echo
